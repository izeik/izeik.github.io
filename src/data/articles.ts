export function splitEnglishSentences(text: string) {
  // A closing quote belongs to its sentence. Keep a trailing speech tag ("he asked") with the dialogue.
  return text.trim().split(/(?<=[.!?][”"]?)\s+(?=[A-Z0-9“"])/u);
}

function splitChineseSentences(text: string) {
  return text.match(/[^。！？]+[。！？]/g)?.map((sentence) => sentence.trim()) ?? [text];
}

